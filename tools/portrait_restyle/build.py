"""Build the exhibit's ILLUSTRATED medallions from the chosen restyle renders.

Reads selection.json (which render stands for each sitter), composes each into
the exhibit's medallion template with the SAME drawing code as the photographs
(tools/fetch_conductor_portraits.py compose()), and writes
app/static/exhibit/portraits/<slug>.webp plus credits.json.

PROVENANCE RUNS BACK THE OTHER WAY. The photo build stamps `digitalCapture`;
these assets are generated by a model (denoise 1.0: every pixel is redrawn,
conditioned on the photograph), so the XMP says `trainedAlgorithmicMedia`, names
the model, seed, and prompt template, and still credits the photograph the
illustration was made from, because a CC BY / BY-SA photograph's credit travels
with its derivatives. credits.json keeps every photo field and adds
`illustrated` and `illustration`, which the exhibit's credit line reads.

THE PHOTOGRAPHS ARE KEPT. Before the first overwrite, the photo medallions and
their credits.json are copied to portraits/photo/ (user, 2026-11-27). Placeholder
medallions depict nobody and are left exactly as they are.

usage: ~/ComfyUI/.venv/bin/python -I build.py
"""
import json, os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))
from common import FACTS, LOG, OUT, PORTRAITS, REPO, SOURCES  # noqa: E402
from fetch_conductor_portraits import CANVAS, _xml, compose  # noqa: E402  (drawing only; no network)
from PIL import Image  # noqa: E402

SELECTION = os.path.join(HERE, "selection.json")
CREDITS = os.path.join(PORTRAITS, "credits.json")
PHOTO_DIR = os.path.join(PORTRAITS, "photo")
MODEL = "Qwen-Image-Edit-2511 (Q6_K GGUF) with the Lightning 4-step LoRA, run locally"

XMP_ILLUSTRATION = (
    '<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>'
    '<x:xmpmeta xmlns:x="adobe:ns:meta/">'
    '<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
    '<rdf:Description rdf:about=""'
    ' xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"'
    ' xmlns:xmpRights="http://ns.adobe.com/xap/1.0/rights/"'
    ' xmlns:dc="http://purl.org/dc/elements/1.1/">'
    "<Iptc4xmpExt:DigitalSourceType>"
    "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"
    "</Iptc4xmpExt:DigitalSourceType>"
    "<dc:creator><rdf:Seq><rdf:li>{artist} (source photograph)</rdf:li>"
    "<rdf:li>{model} (illustration)</rdf:li></rdf:Seq></dc:creator>"
    "<dc:rights><rdf:Alt><rdf:li xml:lang=\"x-default\">{licence}</rdf:li></rdf:Alt></dc:rights>"
    "<dc:source>{source}</dc:source>"
    "<xmpRights:WebStatement>{licence_url}</xmpRights:WebStatement>"
    "<dc:description><rdf:Alt><rdf:li xml:lang=\"x-default\">{description}</rdf:li>"
    "</rdf:Alt></dc:description>"
    "</rdf:Description></rdf:RDF></x:xmpmeta><?xpacket end=\"w\"?>"
)

DESC = (
    "AI-generated illustration of {sitter}, made by {model} (prompt template {template}, "
    "seed {seed}) from the photograph by {artist}, {licence}, Wikimedia Commons ({source}). "
    "Not a photograph. Set in the Signature Sound Vienna exhibit's medallion frame; "
    "display only, no fact is derived from it."
)


def load(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def keep_photographs():
    """Copy the photo medallions and their credits aside once, before any overwrite."""
    if os.path.isdir(PHOTO_DIR):
        return
    os.makedirs(PHOTO_DIR)
    for name in os.listdir(PORTRAITS):
        if name.endswith(".webp") or name == "credits.json":
            shutil.copy2(os.path.join(PORTRAITS, name), os.path.join(PHOTO_DIR, name))
    print(f"photographs kept in {os.path.relpath(PHOTO_DIR, REPO)}")


def recipe(render_name):
    """The logged recipe of one render (renders.jsonl), so the credit can cite it."""
    want = os.path.join("tools", ".cache", "portrait-restyle", "out", render_name + ".png")
    with open(LOG, encoding="utf-8") as fh:
        for line in fh:
            rec = json.loads(line)
            if rec["out"] == want:
                return rec
    sys.exit(f"{render_name}: not in {os.path.relpath(LOG, REPO)} — render it with render.py first")


def main():
    keep_photographs()
    sel = load(SELECTION)["sitters"]
    names = {k: v["name"] for k, v in load(SOURCES)["conductors"].items()}
    photo_credits = load(os.path.join(PHOTO_DIR, "credits.json"))
    credits = photo_credits["conductors"]
    facts = load(FACTS)

    for slug, pick in sel.items():
        name = names[slug]
        rec = recipe(pick["render"])
        entry = dict(credits[name])
        variant = facts.get(rec["slug"], {}).get("source") if "." in rec["slug"] else None
        photo_file = load(SOURCES)["conductors"][slug]["file"]
        if variant and variant.get("file", photo_file) != photo_file:
            # illustrated from ANOTHER photograph than the photo medallion's (a crop-only
            # variant reframes the same photograph and keeps its credit unchanged)
            entry.update(artist=variant["author"], licence=variant["licence"],
                         licenceUrl=variant.get("licenceUrl"), source=variant["sourceUrl"],
                         photoYear=variant["year"], restrictions=variant.get("restrictions"),
                         attribution=not variant["licence"].lower().startswith(("public domain", "cc0")))
        img = Image.open(os.path.join(REPO, rec["out"]))
        asset = compose(img, size=CANVAS)
        desc = DESC.format(sitter=name, model=MODEL, template=rec["template_file"],
                           seed=rec["seed"], artist=entry["artist"] or "an unrecorded photographer",
                           licence=entry["licence"], source=entry["source"])
        out_path = os.path.join(PORTRAITS, f"{slug}.webp")
        asset.save(out_path, "WEBP", quality=88, method=6, xmp=XMP_ILLUSTRATION.format(
            artist=_xml(entry["artist"] or "unrecorded"), model=_xml(MODEL),
            licence=_xml(entry["licence"]), source=_xml(entry["source"]),
            licence_url=_xml(entry.get("licenceUrl") or ""), description=_xml(desc)).encode())
        entry["illustrated"] = True
        entry["illustration"] = {
            "model": MODEL, "template": rec["template_file"],
            "templateSha256": rec["template_sha256"], "seed": rec["seed"],
            "render": pick["render"], "log": os.path.relpath(LOG, REPO),
            "sourcePhoto": rec["slug"],
        }
        credits[name] = entry
        print(f"  {slug:14s} <- {pick['render']:34s} {os.path.getsize(out_path) // 1024:3d} KB")

    out = dict(photo_credits, conductors=credits, note=(
        "Generated by tools/portrait_restyle/build.py and COMMITTED: the kiosk has no network, "
        "and CC BY/BY-SA require the credit to travel with the image and its derivatives. "
        "Entries with `illustrated` are AI-generated illustrations made from the credited "
        "photograph; the photo medallions and their credits are kept in portraits/photo/."))
    with open(CREDITS, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"credits.json written; now re-run tools/prep_exhibit_concerts.py")


if __name__ == "__main__":
    main()
